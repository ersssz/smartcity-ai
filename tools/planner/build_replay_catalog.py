"""Offline adapter of retained real OSM paths and separately authored editorial content.

This is a deliberately bounded source-replay adapter, not current-origin, field,
city-wide routing or live generation acceptance. No network or inferred connector.
"""
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from tools.data.walking import WalkingGraph

PINS = {
    'apps/mobile/src/walk/preparedWalk.json': '4c361722fd6eefc31488431ca84e8bf9fe17fa09b83d193256381512ba86422b',
    'evidence/first-walk/routing-source.json': '7c71e91aa760e046c7a706ebd68fca4954d71fd457fa7d8c1d7a744fb9e5799b',
}

def main():
    inputs = {}
    for name, expected in PINS.items():
        raw = (ROOT / name).read_bytes()
        if hashlib.sha256(raw).hexdigest() != expected:
            raise ValueError('Pinned source changed: ' + name)
        inputs[name] = json.loads(raw)
    walk = inputs['apps/mobile/src/walk/preparedWalk.json']
    witness = inputs['evidence/first-walk/routing-source.json']
    graph = WalkingGraph(witness)
    paths = []
    for first in walk['stops']:
        for last in walk['stops']:
            if first['id'] == last['id']:
                continue
            route = graph.route(int(first['osmNodeId']), int(last['osmNodeId']))
            if route['kind'] != 'technical_path':
                raise ValueError('Actual public anchor pair has no retained source path')
            paths.append({'fromId': first['id'], 'toId': last['id'], **route})
    # The existing authored manuscripts deliberately use these four paragraph roles.
    # Fail on a new editorial layout rather than guessing which new claim is a fact.
    for stop in walk['stops']:
        for locale in ('ru', 'kk', 'en'):
            if len(stop['story'][locale].split('\n\n')) != 4:
                raise ValueError('Editorial paragraph roles need explicit review')
    result = {'pins': PINS, 'prepared': walk, 'paths': paths, 'provenance': witness['provenance']}
    output = ROOT / 'packages/walk-planner/src/catalog.generated.ts'
    text = '// Generated by tools/planner/build_replay_catalog.py. Retained source replay, not field evidence.\nexport default ' + json.dumps(result, ensure_ascii=False, indent=2) + ';\n'
    if '--check' in sys.argv:
        if not output.exists() or output.read_text(encoding='utf-8') != text:
            raise ValueError('Replay catalog is missing or stale')
    else:
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(text, encoding='utf-8', newline='\n')
    print(json.dumps({'paths': len(paths), 'stops': len(walk['stops']), 'sha256': hashlib.sha256(text.encode()).hexdigest()}))

if __name__ == '__main__':
    main()
